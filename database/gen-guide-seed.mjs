// Writes database/guide_seed.sql from the JSON the app ships with. Run: node database/gen-guide-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { guideToRows, buildSeedSql } from "../apps/web/lib/guide/rows.ts";

const read = (f) => JSON.parse(readFileSync(new URL(`../apps/web/lib/data/${f}`, import.meta.url), "utf8"));
const sql = buildSeedSql(guideToRows(read("candidates.json"), read("coverage.json"), read("candidate-extras.json")));
writeFileSync(new URL("./guide_seed.sql", import.meta.url), "-- Generated by database/gen-guide-seed.mjs from apps/web/lib/data. Do not edit by hand.\n" + sql);
console.log("wrote database/guide_seed.sql,", sql.split("\n").length, "lines");
