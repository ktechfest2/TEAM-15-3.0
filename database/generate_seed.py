"""Generate synthetic polling units (DEMO data). Run: python3 database/generate_seed.py
Writes apps/web/lib/data/units.json and database/seed.sql with identical, deterministic ids."""
import json, os, uuid

ROOT = os.path.join(os.path.dirname(__file__), "..")
NS = uuid.UUID("6f0d7c2e-0000-4000-8000-00000000d3a0")
STATES = {
    "Lagos": ("LA", {"Ikeja": "IKJ", "Surulere": "SUR"}),
    "FCT": ("FC", {"Abuja Municipal": "AMA", "Bwari": "BWR"}),
    "Kano": ("KN", {"Nassarawa": "NAS", "Fagge": "FAG"}),
}
KINDS = ["Primary School", "Town Hall", "Market Square", "Health Centre", "Community Hall", "Open Ground"]
units = []
for state, (sab, lgas) in STATES.items():
    for lga, lab in lgas.items():
        for w in range(1, 5):
            special = state == "Lagos" and lga == "Ikeja" and w == 4
            for i in range(6):
                num = 12 + i if special else i + 1
                kind = KINDS[i]
                name = f"{lga} {kind}" if not special or i > 2 else ["Ikeja Primary School", "Ikeja Town Hall", "Ikeja Market Square"][i]
                code = f"{sab}-{lab}-{w:02d}-{num:03d}"
                units.append({
                    "id": str(uuid.uuid5(NS, code)), "code": code, "name": name,
                    "ward": f"Ward {w:02d}", "lga": lga, "state": state, "source": "demo_synthetic",
                })
with open(os.path.join(ROOT, "apps/web/lib/data/units.json"), "w") as f:
    json.dump(units, f, indent=1)
q = lambda s: "'" + s.replace("'", "''") + "'"
rows = ",\n".join(f"  ({q(u['id'])}, {q(u['code'])}, {q(u['name'])}, {q(u['ward'])}, {q(u['lga'])}, {q(u['state'])}, 'demo_synthetic')" for u in units)
with open(os.path.join(ROOT, "database/seed.sql"), "w") as f:
    f.write("-- Synthetic DEMO polling units. Generated by database/generate_seed.py\n"
            "insert into public.polling_units (id, code, name, ward, lga, state, source) values\n" + rows + "\non conflict (code) do nothing;\n")
print(len(units), "units")
